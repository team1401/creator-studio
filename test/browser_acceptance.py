"""Optional Chromium browser acceptance; uses temporary test data, never the real studio."""
import json, os, secrets, subprocess, tempfile
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'verification'
OUT.mkdir(exist_ok=True)
with tempfile.TemporaryDirectory(prefix='studio-browser-', dir=os.environ.get('TMPDIR')) as temp:
    password = secrets.token_urlsafe(32)
    (Path(temp) / 'password').write_text(password)
    os.chmod(Path(temp) / 'password', 0o600)
    server = subprocess.Popen(['node', 'server.mjs'], cwd=ROOT, env={**os.environ, 'STUDIO_DATA': temp, 'PORT': '0'}, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    try:
        base = server.stdout.readline().strip().split(' at ')[-1]
        with sync_playwright() as p:
            browser = p.chromium.launch(headless=True)
            page = browser.new_page(viewport={'width': 1440, 'height': 1000})
            errors = []
            page.on('pageerror', lambda e: errors.append(str(e)))
            page.goto(base)
            expect(page.get_by_role('heading', name='A place for the work.')).to_be_visible()
            page.get_by_label('Studio password').fill(password)
            page.get_by_role('button', name='Open your studio').click()
            expect(page.get_by_role('button', name='Choose your first character')).to_be_visible()
            page.screenshot(path=str(OUT / 'desktop-empty.png'), full_page=True)
            page.set_viewport_size({'width': 390, 'height': 844})
            page.screenshot(path=str(OUT / 'mobile-empty.png'), full_page=True)
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
            page.get_by_role('button', name='Choose your first character').click()
            page.get_by_label('Character name').fill('TEST ONLY <img src=x onerror=alert(1)>')
            page.get_by_label('Voice and personality').fill('Thoughtful and precise')
            page.get_by_label('Rules, disclosure and boundaries').fill('Fictional persona; no false claims')
            page.get_by_role('button', name='Save character').click()
            expect(page.get_by_role('heading', name='TEST ONLY <img src=x onerror=alert(1)>', exact=True)).to_be_visible()
            assert page.locator('img').count() == 0
            page.get_by_role('link', name='Studio overview').click()
            page.get_by_role('button', name='Create your first project').click()
            page.get_by_label('Project title').fill('TEST ONLY · Unpublished short')
            page.get_by_label('Character', exact=True).select_option(label='TEST ONLY <img src=x onerror=alert(1)>')
            page.get_by_label('Brief: audience, format, goal').fill('A private test of the production workflow.')
            page.get_by_role('button', name='Save project').click()
            expect(page.get_by_role('heading', name='TEST ONLY · Unpublished short', exact=True)).to_be_visible()
            page.get_by_role('button', name='Edit', exact=True).click()
            page.get_by_label('Current stage').select_option('review')
            page.get_by_label('Script / page copy').fill('An unpublished script revision.')
            page.get_by_role('button', name='Save project').click()
            page.get_by_role('button', name='Add review action').click()
            page.get_by_label('Decision title').fill('TEST ONLY · Check disclosure')
            page.get_by_label('Why you are needed').fill('Confirm truthful framing')
            page.get_by_label('What to do, step by step').fill('Read the script and confirm the fictional disclosure')
            page.get_by_label('What happens next').fill('Revise the draft manually; do not publish')
            page.get_by_role('button', name='Save action').click()
            page.get_by_label('Review note').fill('Needs a clearer disclosure')
            page.get_by_role('button', name='Request changes').click()
            expect(page.get_by_text('Changes requested', exact=True)).to_be_visible()
            page.get_by_label('Review note').fill('Disclosure revised, editorial approval only')
            page.get_by_role('button', name='Approve locally').click()
            expect(page.get_by_text('Approved', exact=True)).to_be_visible()
            page.get_by_role('link', name='Asset library', exact=True).click()
            page.get_by_role('button', name='+ Upload asset', exact=True).click()
            page.get_by_label('File, maximum 10 MiB').set_input_files({'name':'reference.txt','mimeType':'text/plain','buffer':b'TEST ONLY private reference'})
            page.get_by_label('Project', exact=True).select_option(label='TEST ONLY · Unpublished short')
            page.get_by_role('button', name='Upload privately').click()
            expect(page.get_by_role('heading', name='reference.txt', exact=True)).to_be_visible()
            page.get_by_role('button', name='Upload next version').click()
            page.get_by_label('File, maximum 10 MiB').set_input_files({'name':'reference-v2.txt','mimeType':'text/plain','buffer':b'TEST ONLY revised reference'})
            page.get_by_role('button', name='Upload privately').click()
            expect(page.get_by_text('Version 2', exact=True)).to_be_visible()
            page.get_by_role('link', name='Agent handoffs', exact=True).click()
            page.get_by_role('button', name='New handoff', exact=False).first.click()
            page.get_by_label('Handoff title').fill('TEST ONLY · Manual review')
            page.get_by_label('Bounded task and constraints').fill('Read the script; do not publish or spend')
            page.get_by_role('button', name='Save handoff').click()
            expect(page.get_by_text('Awaiting manual', exact=True)).to_be_visible()
            page.get_by_role('button', name='Edit', exact=True).click()
            page.get_by_label('Local job status').select_option('manual_complete')
            page.get_by_label('Actual manual result / evidence').fill('TEST ONLY old completion https://example.test/draft-A')
            page.get_by_role('button', name='Save handoff').click()
            expect(page.get_by_text('Manual complete', exact=True)).to_be_visible()
            page.get_by_role('button', name='Edit', exact=True).click()
            page.get_by_label('Bounded task and constraints').fill('Review different draft B')
            page.get_by_role('button', name='Save handoff').click()
            expect(page.get_by_text('Awaiting manual', exact=True)).to_be_visible()
            expect(page.get_by_text('TEST ONLY old completion https://example.test/draft-A', exact=True)).to_have_count(0)
            page.get_by_role('button', name='Edit', exact=True).click()
            expect(page.get_by_label('Actual manual result / evidence')).to_have_value('')
            page.get_by_role('link', name='Services & tools', exact=True).click()
            expect(page.get_by_text('Argus: not connected.', exact=True)).to_be_visible()
            expect(page.get_by_text('Automatic execution: disabled.', exact=False)).to_be_visible()
            expect(page.get_by_text('Desktop runtime repaired and native input verified;', exact=False)).to_be_visible()
            expect(page.get_by_text('Not connected', exact=True)).to_have_count(3)
            page.get_by_role('link', name='Production', exact=True).click()
            expect(page.get_by_role('heading', name='TEST ONLY · Unpublished short', exact=True)).to_be_visible()
            page.screenshot(path=str(OUT / 'mobile-production-test.png'), full_page=True)
            for name in ['Needs you', 'Characters', 'Asset library', 'Agent handoffs', 'Services & tools', 'Activity journal']:
                page.get_by_role('link', name=name, exact=False).first.click()
                page.wait_for_timeout(80)
                assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), name
            assert not errors, errors
            browser.close()
            print(json.dumps({'browser':'Chromium','viewport':'390x844 and 1440x1000','passed':['login','onboarding','character create','XSS rendered as text','project create/edit','review changes/approve','upload and version','manual job completion and scope reopening clears evidence','explicit integration capability labels','service labels','mobile overflow all sections'],'page_errors':errors,'screenshots':str(OUT)}, indent=2))
    finally:
        server.terminate()
        server.wait(timeout=10)
